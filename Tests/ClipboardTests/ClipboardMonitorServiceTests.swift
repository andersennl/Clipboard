import AppKit
import XCTest
@testable import Clipboard

@MainActor
final class ClipboardMonitorServiceTests: XCTestCase {
    func testUnchangedChangeCountDoesNotCapture() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: "New text")
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        service.pollOnce()

        XCTAssertTrue(captures.isEmpty)
    }

    func testNilStringDoesNotCapture() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(text: nil)
        service.pollOnce()

        XCTAssertTrue(captures.isEmpty)
    }

    func testWhitespaceOnlyStringDoesNotCapture() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(text: " \n\t ")
        service.pollOnce()

        XCTAssertTrue(captures.isEmpty)
    }

    func testValidTextCapturesDeterministicItemWithSourceFallback() throws {
        let date = Date(timeIntervalSince1970: 42)
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard, date: date, sourceApplication: nil)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(text: "Captured")
        service.pollOnce()

        let item = try XCTUnwrap(captures.first)
        XCTAssertEqual(captures.count, 1)
        XCTAssertEqual(item.text, "Captured")
        XCTAssertEqual(item.createdAt, date)
        XCTAssertEqual(item.sourceAppName, "Unknown App")
        XCTAssertEqual(item.sourceBundleID, "unknown")
    }

    func testTextOver100WordsCapturesWithoutTruncating() throws {
        let longText = makeLongText(wordCount: 125)
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(text: longText)
        service.pollOnce()

        let item = try XCTUnwrap(captures.first)
        XCTAssertEqual(captures.count, 1)
        XCTAssertEqual(item.text, longText)
    }

    func testRepeatedTextStillCapturesOnNewPasteboardChanges() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(text: "Duplicate")
        service.pollOnce()
        pasteboard.advance(text: "Duplicate")
        service.pollOnce()

        XCTAssertEqual(captures.map(\.text), ["Duplicate", "Duplicate"])
    }

    func testSuppressNextCaptureDoesNotSuppressLaterMatchingTextAfterDifferentChange() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        service.suppressNextCapture(text: "A")
        pasteboard.advance(text: "B")
        service.pollOnce()
        pasteboard.advance(text: "A")
        service.pollOnce()

        XCTAssertEqual(captures.map(\.text), ["B", "A"])
    }

    func testSuppressNextCaptureSkipsMatchingTextOnce() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        service.suppressNextCapture(text: "A")
        pasteboard.advance(text: "A")
        service.pollOnce()
        pasteboard.advance(text: "A")
        service.pollOnce()

        XCTAssertEqual(captures.map(\.text), ["A"])
    }

    func testConcealedContentIsNotCaptured() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        pasteboard.advance(
            text: "hunter2",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        )
        service.pollOnce()

        XCTAssertTrue(captures.isEmpty)
    }

    func testTransientAndAutoGeneratedContentIsNotCaptured() {
        let markers = [
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "de.petermaurer.TransientPasteboardType",
            "com.agilebits.onepassword"
        ]

        for marker in markers {
            let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
            let service = makeService(pasteboard: pasteboard)
            var captures: [ClipboardItem] = []
            service.onCapture = { captures.append($0) }

            pasteboard.advance(
                text: "Ignore me",
                types: [.string, NSPasteboard.PasteboardType(marker)]
            )
            service.pollOnce()

            XCTAssertTrue(captures.isEmpty, "Expected no capture for marker \(marker)")
        }
    }

    func testConcealedContentDoesNotConsumeThePendingPasteSuppression() {
        let pasteboard = FakeReadablePasteboard(changeCount: 0, text: nil)
        let service = makeService(pasteboard: pasteboard)
        var captures: [ClipboardItem] = []
        service.onCapture = { captures.append($0) }

        service.suppressNextCapture(text: "Pasted by the app")
        pasteboard.advance(
            text: "hunter2",
            types: [.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")]
        )
        service.pollOnce()

        pasteboard.advance(text: "Pasted by the app")
        service.pollOnce()

        XCTAssertTrue(captures.isEmpty)
    }

    private func makeService(
        pasteboard: FakeReadablePasteboard,
        date: Date = Date(timeIntervalSince1970: 1),
        sourceApplication: ClipboardSourceApplication? = ClipboardSourceApplication(
            localizedName: "Tests",
            bundleIdentifier: "tests"
        )
    ) -> ClipboardMonitorService {
        ClipboardMonitorService(
            pasteboard: pasteboard,
            dateProvider: { date },
            sourceApplicationProvider: { sourceApplication }
        )
    }

    private func makeLongText(wordCount: Int) -> String {
        (1...wordCount)
            .map { "word\($0)" }
            .joined(separator: " ")
    }
}

private final class FakeReadablePasteboard: ClipboardPasteboardReading {
    private(set) var changeCount: Int
    private var text: String?
    private(set) var types: [NSPasteboard.PasteboardType]?

    init(changeCount: Int, text: String?) {
        self.changeCount = changeCount
        self.text = text
        self.types = [.string]
    }

    func string(forType dataType: NSPasteboard.PasteboardType) -> String? {
        text
    }

    func advance(text: String?, types: [NSPasteboard.PasteboardType]? = [.string]) {
        changeCount += 1
        self.text = text
        self.types = types
    }
}
