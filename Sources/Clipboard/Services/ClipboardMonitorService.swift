import AppKit
import Foundation

@MainActor
protocol ClipboardMonitoring: AnyObject {
    var onCapture: ((ClipboardItem) -> Void)? { get set }

    func start()
    func stop()
    func suppressNextCapture(text: String)
}

protocol ClipboardPasteboardReading: AnyObject {
    var changeCount: Int { get }
    var types: [NSPasteboard.PasteboardType]? { get }

    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
}

extension NSPasteboard: ClipboardPasteboardReading {}

struct ClipboardSourceApplication {
    let localizedName: String?
    let bundleIdentifier: String?
}

@MainActor
final class ClipboardMonitorService: ClipboardMonitoring {
    private let pasteboard: ClipboardPasteboardReading
    private let dateProvider: () -> Date
    private let sourceApplicationProvider: () -> ClipboardSourceApplication?
    private var timer: Timer?
    private var lastChangeCount: Int
    private var suppressedText: String?

    var onCapture: ((ClipboardItem) -> Void)?

    init(
        pasteboard: ClipboardPasteboardReading = NSPasteboard.general,
        dateProvider: @escaping () -> Date = { .now },
        sourceApplicationProvider: @escaping () -> ClipboardSourceApplication? = {
            let application = NSWorkspace.shared.frontmostApplication
            return ClipboardSourceApplication(
                localizedName: application?.localizedName,
                bundleIdentifier: application?.bundleIdentifier
            )
        }
    ) {
        self.pasteboard = pasteboard
        self.dateProvider = dateProvider
        self.sourceApplicationProvider = sourceApplicationProvider
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }

        lastChangeCount = pasteboard.changeCount

        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pollOnce()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func suppressNextCapture(text: String) {
        suppressedText = text
    }

    func pollOnce() {
        guard pasteboard.changeCount != lastChangeCount else { return }

        lastChangeCount = pasteboard.changeCount

        // Leaves `suppressedText` pending: the app's own paste-back may still be in flight.
        guard !isMarkedAsPrivate else { return }

        guard let text = pasteboard.string(forType: .string) else { return }

        let normalizedText = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !normalizedText.isEmpty else { return }

        if suppressedText == text {
            suppressedText = nil
            return
        }

        suppressedText = nil

        let sourceApplication = sourceApplicationProvider()
        let item = ClipboardItem(
            text: text,
            createdAt: dateProvider(),
            sourceAppName: sourceApplication?.localizedName ?? ClipboardItem.unknownSourceAppName,
            sourceBundleID: sourceApplication?.bundleIdentifier ?? "unknown"
        )

        onCapture?(item)
    }

    private var isMarkedAsPrivate: Bool {
        guard let types = pasteboard.types else { return false }

        return types.contains { Self.privatePasteboardTypes.contains($0.rawValue) }
    }

    // macOS has no system API that tells a clipboard manager to skip an item, so password
    // managers and similar apps add one of these marker types instead. The convention is
    // documented at http://nspasteboard.org — the first three are the current identifiers,
    // the rest are legacy ones that older apps still write.
    private static let privatePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword"
    ]
}
